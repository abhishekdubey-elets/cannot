"""Push UGEN kernels and datasets to Kaggle from the local machine.

Usage:
  python push_kernel.py src            # upload/refresh the ugen-src code dataset
  python push_kernel.py data           # upload/refresh the ugen-data frozen benchmarks
  python push_kernel.py s0             # push the smoke-test kernel (M1, 8 items/benchmark)
  python push_kernel.py g1 [--resume-from KERNEL]   # full M1 sweep
  python push_kernel.py g2|g3|g4 [--resume-from KERNEL]
  python push_kernel.py status <slug>  # kernel status
  python push_kernel.py fetch <slug>   # download kernel output into outputs/<slug>/

Every push writes the exact kernel script into experiments/pushed/<name>.py (append-only
audit trail).
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent          # .../ugen
REPO = PROJECT.parent          # .../abhi
USER = "abhishekakgec"

SRC_DS = f"{USER}/ugen-src"
DATA_DS = f"{USER}/ugen-data"

MODELS = {
    # run: (kernel suffix, model_source, path hint, model column name)
    "m1": ("qwen25-3b", "qwen-lm/qwen2.5/Transformers/3b-instruct/1", "3b-instruct",
           "Qwen2.5-3B-Instruct"),
    "m2": ("llama32-3b", "metaresearch/llama-3.2/transformers/3b-instruct/1", "3b-instruct",
           "Llama-3.2-3B-Instruct"),
    "m3": ("gemma3-4b", "google/gemma-3/transformers/gemma-3-4b-it/1", "gemma-3-4b-it",
           "Gemma-3-4B-IT"),
    "m4": ("phi35-mini", "Microsoft/phi-3/transformers/phi-3.5-mini-instruct/1",
           "phi-3.5-mini", "Phi-3.5-mini-instruct"),
}

BENCHMARKS = ["mmlu", "mmlu_pro", "truthfulqa", "gpqa", "gsm8k", "svamp", "multiarith",
              "commonsenseqa", "arc_challenge", "strategyqa", "bbh", "musr",
              "humaneval", "mbpp"]

KERNEL_TEMPLATE = '''"""UGEN kernel — generated by push_kernel.py; do not edit by hand."""
import sys
sys.path.insert(0, "/kaggle/input/ugen-src")
from ugen.pipeline.runner import main

main(model_hint={hint!r}, model_name={model_name!r},
     benchmarks={benchmarks!r},
     data_dir="/kaggle/input/ugen-data/datasets",
     seed=0, limit={limit!r})
'''


def sh(*args, check=True):
    print("+", " ".join(args))
    r = subprocess.run(list(args), text=True, capture_output=True)
    print(r.stdout[-3000:] if r.stdout else "", r.stderr[-2000:] if r.stderr else "")
    if check and r.returncode != 0:
        raise SystemExit(f"command failed: {args}")
    return r


def upload_src():
    with tempfile.TemporaryDirectory() as td:
        pkg = Path(td) / "ugen"
        (pkg / "pipeline").mkdir(parents=True)
        for f in (PROJECT / "pipeline").glob("*.py"):
            shutil.copy(f, pkg / "pipeline" / f.name)
        tests = pkg / "pipeline" / "tests"
        tests.mkdir()
        for f in (PROJECT / "pipeline" / "tests").glob("*.py"):
            shutil.copy(f, tests / f.name)
        (pkg / "__init__.py").write_text("", encoding="utf-8")
        meta = dict(title="ugen-src", id=SRC_DS, licenses=[dict(name="CC0-1.0")])
        (Path(td) / "dataset-metadata.json").write_text(json.dumps(meta), encoding="utf-8")
        _create_or_version(td, SRC_DS, "src update")


def upload_data():
    with tempfile.TemporaryDirectory() as td:
        dst = Path(td) / "datasets"
        dst.mkdir()
        for f in (PROJECT / "datasets").glob("*"):
            if f.suffix in (".jsonl", ".json"):
                shutil.copy(f, dst / f.name)
        meta = dict(title="ugen-data", id=DATA_DS, licenses=[dict(name="CC0-1.0")])
        (Path(td) / "dataset-metadata.json").write_text(json.dumps(meta), encoding="utf-8")
        _create_or_version(td, DATA_DS, "frozen benchmark subsets")


def _create_or_version(td, ds_id, msg):
    r = sh("kaggle", "datasets", "status", ds_id, check=False)
    if r.returncode == 0 and "not found" not in (r.stdout + r.stderr).lower():
        sh("kaggle", "datasets", "version", "-p", td, "-m", msg, "--dir-mode", "zip")
    else:
        sh("kaggle", "datasets", "create", "-p", td, "--dir-mode", "zip")


def push_run(run, limit=None, resume_from=None, suffix=""):
    kname, model_source, hint, model_name = MODELS[run]
    slug = f"ugen-{'s0-' if limit else ''}{kname}{suffix}"
    script = KERNEL_TEMPLATE.format(hint=hint, model_name=model_name,
                                    benchmarks=BENCHMARKS, limit=limit)
    pushed = HERE / "pushed"
    pushed.mkdir(exist_ok=True)
    (pushed / f"{slug}.py").write_text(script, encoding="utf-8")   # audit trail

    with tempfile.TemporaryDirectory() as td:
        (Path(td) / f"{slug}.py").write_text(script, encoding="utf-8")
        meta = dict(
            id=f"{USER}/{slug}", title=slug, code_file=f"{slug}.py",
            language="python", kernel_type="script", is_private=True,
            enable_gpu=True, enable_tpu=False, enable_internet=False,
            dataset_sources=[SRC_DS, DATA_DS],
            kernel_sources=[resume_from] if resume_from else [],
            competition_sources=[], model_sources=[model_source])
        (Path(td) / "kernel-metadata.json").write_text(json.dumps(meta, indent=1),
                                                       encoding="utf-8")
        sh("kaggle", "kernels", "push", "-p", td)
    print(f"pushed -> https://www.kaggle.com/code/{USER}/{slug}")
    return slug


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd")
    ap.add_argument("arg", nargs="?")
    ap.add_argument("--resume-from")
    ap.add_argument("--limit", type=int)
    a = ap.parse_args()
    if a.cmd == "src":
        upload_src()
    elif a.cmd == "data":
        upload_data()
    elif a.cmd == "s0":
        push_run("m1", limit=a.limit or 8)
    elif a.cmd in MODELS:
        push_run(a.cmd, limit=a.limit, resume_from=a.resume_from)
    elif a.cmd == "g1":
        push_run("m1", resume_from=a.resume_from)
    elif a.cmd == "g2":
        push_run("m2", resume_from=a.resume_from)
    elif a.cmd == "g3":
        push_run("m3", resume_from=a.resume_from)
    elif a.cmd == "g4":
        push_run("m4", resume_from=a.resume_from)
    elif a.cmd == "status":
        sh("kaggle", "kernels", "status", f"{USER}/{a.arg}")
    elif a.cmd == "fetch":
        out = PROJECT / "outputs" / a.arg
        out.mkdir(parents=True, exist_ok=True)
        sh("kaggle", "kernels", "output", f"{USER}/{a.arg}", "-p", str(out))
    else:
        raise SystemExit(f"unknown cmd {a.cmd}")


if __name__ == "__main__":
    main()
