def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd")
    ap.add_argument("arg", nargs="?")
    ap.add_argument("--resume-from")
    ap.add_argument("--limit", type=int)
    ap.add_argument("--suffix", default="")
    a = ap.parse_args()
    if a.resume_from and not a.suffix:
        a.suffix = "-r2"          # a kernel cannot attach its own output — new slug
    if a.cmd == "prev":
        upload_prev()
    elif a.cmd == "src":
        upload_src()
    elif a.cmd == "data":
        upload_data()
    elif a.cmd == "s0":
        push_run("m1", limit=a.limit or 8)
    elif a.cmd in MODELS:
        push_run(a.cmd, limit=a.limit, resume_from=a.resume_from, suffix=a.suffix)
    elif a.cmd == "g1":
        push_run("m1", resume_from=a.resume_from, suffix=a.suffix)
    elif a.cmd == "g2":
        push_run("m2", resume_from=a.resume_from, suffix=a.suffix)
    elif a.cmd == "g3":
        push_run("m3", resume_from=a.resume_from, suffix=a.suffix)
    elif a.cmd == "g4":
        push_run("m4", resume_from=a.resume_from, suffix=a.suffix)
    elif a.cmd == "probe":
        push_probe(a.arg)
    elif a.cmd == "probe-wording":
        push_probe_wording(a.arg or "m1")
    elif a.cmd == "seeds":
        push_seeds()
    elif a.cmd == "status":
        sh("kaggle", "kernels", "status", f"{USER}/{a.arg}")
    elif a.cmd == "fetch":
        out = PROJECT / "outputs" / a.arg
        out.mkdir(parents=True, exist_ok=True)
        sh("kaggle", "kernels", "output", f"{USER}/{a.arg}", "-p", str(out))
    else:
        raise SystemExit(f"unknown cmd {a.cmd}")


if __name__ == "__main__":
    main()
